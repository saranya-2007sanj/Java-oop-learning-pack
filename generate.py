#!/usr/bin/env python3
"""Automation step (Capstone task 9).

  python tools/generate.py exercises            -> docs/exercises.md (from exercises/Solutions.java)
  python tools/generate.py variations [--n 12 --seed 43]
                                                -> docs/exercise_variations.md (template-based new exercises)
"""
import argparse, pathlib, random, re, textwrap

ROOT = pathlib.Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"


def build_exercises():
    lines = (ROOT / "exercises" / "Solutions.java").read_text().splitlines()
    out = ["# 20 OOP Exercises with Solutions", "",
           "_Auto-generated by `tools/generate.py exercises` from `exercises/Solutions.java`. "
           "Every solution is executed and self-checked by `./run_all.sh`._", ""]
    block, head, count = None, None, 0
    for line in lines:
        m = re.match(r"\s*// @EX (\d+) \| (.*?) \| (.*)", line)
        if m:
            head, block = m.groups(), []
            continue
        if line.strip() == "// @END" and block is not None:
            num, concept, task = head
            code = textwrap.dedent("\n".join(block)).strip("\n")
            out += [f"## Exercise {num} - {concept}", "", f"**Task:** {task}", "",
                    "<details><summary>Solution</summary>", "", "```java", code, "```", "</details>", ""]
            block, count = None, count + 1
            continue
        if block is not None:
            block.append(line)
    (DOCS / "exercises.md").write_text("\n".join(out))
    print(f"wrote docs/exercises.md ({count} exercises)")


# ---------- variation templates ----------
ENTITIES = [  # class, field1, type1, field2, type2, method
    ("Product", "name", "String", "price", "double", "applyDiscount(double percent)"),
    ("Book", "title", "String", "pages", "int", "isLong()"),
    ("Car", "model", "String", "speed", "int", "accelerate(int delta)"),
    ("Student", "name", "String", "marks", "double", "grade()"),
    ("Employee", "name", "String", "salary", "double", "raise(double percent)"),
    ("Ticket", "route", "String", "fare", "double", "applyConcession(double percent)"),
]
HIERARCHIES = [  # base, method, subclasses
    ("Shape", "area", ["Circle", "Square", "Triangle"]),
    ("Vehicle", "fuelCost", ["Bike", "Car", "Truck"]),
    ("Notification", "send", ["Email", "Sms", "PushAlert"]),
    ("Account", "monthlyInterest", ["Savings", "Current", "FixedDeposit"]),
    ("Appliance", "powerUsage", ["Fan", "Heater", "Fridge"]),
]
CONTRACTS = [  # interface, method, holder, implementations
    ("PaymentMethod", "pay(double amount)", "Checkout", ["Upi", "CreditCard", "Cash"]),
    ("SortStrategy", "sort(int[] data)", "Sorter", ["Bubble", "Selection", "Insertion"]),
    ("Logger", "log(String msg)", "Service", ["Console", "File", "Silent"]),
    ("Discount", "apply(double price)", "Cart", ["Festival", "Student", "NoDiscount"]),
]
MISCONCEPTIONS = [
    ("Fields are polymorphic", "Parent p = new Child(); System.out.println(p.name);  // both classes declare 'name'"),
    ("Static methods can be overridden", "Parent p = new Child(); System.out.println(p.who());  // both declare static who()"),
    ("== compares string content", "System.out.println(new String(\"a\") == new String(\"a\"));"),
    ("Java passes objects by reference", "static void f(StringBuilder s){ s = new StringBuilder(\"x\"); }  // does the caller see it?"),
    ("Overloads are chosen by the runtime type", "Object o = \"hi\"; print(o); // print(Object) vs print(String)"),
]


def t_encapsulation(r):
    e, f1, t1, f2, t2, m = r.choice(ENTITIES)
    return (f"Encapsulation - {e}",
            f"Create class `{e}` with private fields `{f1}` ({t1}) and `{f2}` ({t2}). The constructor must reject a negative "
            f"`{f2}` with IllegalArgumentException. Add getters, `toString()` and the method `{m}`. Write checks proving invalid input is rejected.",
            f"class {e} {{\n    private final {t1} {f1};\n    private {t2} {f2};\n    {e}({t1} {f1}, {t2} {f2}) {{\n"
            f"        if ({f2} < 0) throw new IllegalArgumentException(\"{f2} < 0\");\n        this.{f1} = {f1}; this.{f2} = {f2};\n    }}\n"
            f"    // TODO: getters, toString, {m}\n}}")


def t_polymorphism(r):
    base, m, subs = r.choice(HIERARCHIES)
    return (f"Inheritance & polymorphism - {base}",
            f"Create abstract class `{base}` with abstract method `{m}()`. Implement `{subs[0]}`, `{subs[1]}` and `{subs[2]}`. "
            f"Store one of each in a `{base}[]` and call `{m}()` in a single loop. Then add one more subclass WITHOUT changing the loop.",
            f"abstract class {base} {{\n    abstract double {m}();\n}}\nclass {subs[0]} extends {base} {{\n    double {m}() {{ /* TODO */ return 0; }}\n}}")


def t_contract(r):
    i, m, holder, impls = r.choice(CONTRACTS)
    return (f"Interfaces & composition - {holder}",
            f"Define interface `{i}` with `{m}`. Implement it as {', '.join(f'`{x}`' for x in impls)}. Class `{holder}` HAS-A `{i}` "
            f"(constructor injection) and delegates to it. Swap the implementation at run time and test all three.",
            f"interface {i} {{ void {m}; }}\nclass {holder} {{\n    private {i} impl;\n    {holder}({i} impl) {{ this.impl = impl; }}\n    void setImpl({i} impl) {{ this.impl = impl; }}\n}}")


def t_misconception(r):
    claim, snippet = r.choice(MISCONCEPTIONS)
    return (f"Misconception check - \"{claim}\"",
            "Predict the output of the snippet below, explain in one sentence why the claim is true or false, then compile and run it to confirm.",
            snippet)


TEMPLATES = [t_encapsulation, t_polymorphism, t_contract, t_misconception]


def build_variations(n, seed):
    rng = random.Random(seed)
    out = ["# Generated Exercise Variations", "",
           f"_Auto-generated by `tools/generate.py variations --n {n} --seed {seed}`. Change the seed to get a new set._", ""]
    for k in range(n):
        title, task, code = TEMPLATES[k % len(TEMPLATES)](rng)
        out += [f"## V{k + 1:02d} - {title}", "", f"**Task:** {task}", "", "Starter / snippet:", "", "```java", code, "```", ""]
    (DOCS / "exercise_variations.md").write_text("\n".join(out))
    print(f"wrote docs/exercise_variations.md ({n} variations, seed={seed})")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("what", choices=["exercises", "variations"])
    ap.add_argument("--n", type=int, default=12)
    ap.add_argument("--seed", type=int, default=43)
    a = ap.parse_args()
    DOCS.mkdir(exist_ok=True)
    build_exercises() if a.what == "exercises" else build_variations(a.n, a.seed)
